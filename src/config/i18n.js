const TRANSLATIONS = { en: EN, zh: ZH }

function chip(entry) {
  const index = entry.indexOf('|')
  return index < 0 ? [entry, ''] : [entry.slice(0, index), entry.slice(index + 1)]
}

// Array-valued hint entries as kit `[key, desc]` tuples, derived from the catalog.
const HINT_TABLES = Object.fromEntries(
  Object.entries(TRANSLATIONS).map(([language, dict]) => [
    language,
    Object.fromEntries(
      Object.entries(dict)
        .filter(([, value]) => Array.isArray(value))
        .map(([key, value]) => [key, value.map(chip)]),
    ),
  ]),
)

/** Structured `key`/`desc` chips for a hint key; string values become one chip. */
export function hintSegments(language, key) {
  const dict = TRANSLATIONS[language] || TRANSLATIONS.en
  const value = dict[key]
  if (value === undefined)
    return [{ key, desc: '' }]
  if (!Array.isArray(value))
    return [{ key: value, desc: '' }]
  return kitHintSegments(HINT_TABLES, language, key).map(([chipKey, desc]) => ({ key: chipKey, desc }))
}

/** Render segments back to the exact prose line `t()` produces for them. */
export function hintLine(segments) {
  return segments.map(({ key, desc }) => (desc ? `${key} ${desc}` : key)).join('  ·  ')
}

function applyParams(text, params) {
  if (!params)
    return text
  for (const [name, value] of Object.entries(params))
    text = text.replaceAll(`{${name}}`, String(value))
  return text
}

export function t(language, key, params) {
  const dict = TRANSLATIONS[language] || TRANSLATIONS.en
  if (Array.isArray(dict[key]))
    return applyParams(hintLine(hintSegments(language, key)), params)
  return translate(TRANSLATIONS, language, key, params)
}
