const TRANSLATIONS = { en: EN, zh: ZH }

export function t(language, key, params) {
  const dict = TRANSLATIONS[language] || TRANSLATIONS.en
  let text = dict[key]
  if (text === undefined)
    text = key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replaceAll(`{${k}}`, String(v))
    }
  }
  return text
}